// Stance pair at equal 무력, before the cut (scale 1/1, no 합 cap, San11's own 50 landed hits). ai_specials: the AI plays
// (specials allowed) but its stance is pinned; otherwise both sides only command their stance.
static Tally stance_pair(int str, int st0, int st1, bool ai_specials, int n) {
    Tally t;
    Config cfg;
    cfg.dmg_num = 1; cfg.dmg_den = 1; cfg.round_cap = 1000000; cfg.hit_limit = 50;
    if (ai_specials) { cfg.force_stance[0] = st0; cfg.force_stance[1] = st1; }
    Duel d;
    for (int i = 0; i < n; ++i) {
        one_to_one(d, str, str, i % 4, (i / 4) % 4, cfg, sim_seed(i, str * 16 + st0 * 4 + st1));
        const int cmd[2] = {ai_specials ? static_cast<int>(CmdAi) : st0, ai_specials ? static_cast<int>(CmdAi) : st1};
        while (!d.finished) step(d, cmd);
        ++t.win[d.winner]; ++t.n; t.rounds += d.round;
        if (d.end_reason == EndKo) { ++t.ko; t.ko_rounds += d.round; }
    }
    return t;
}
