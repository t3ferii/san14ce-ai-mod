static void fnv(std::uint32_t &h, int v) { h = (h ^ static_cast<std::uint32_t>(v)) * 16777619u; }
static void hash_result(std::uint32_t &h, const RoundResult &r) {
    for (const SideResult &s : r.side) {
        const int v[16] = {s.damage, s.code, s.special, s.special_failed, s.special_preempted, s.swap_out, s.swap_in, s.join_in, s.move,
                           s.hits, s.landed, s.injured, s.hp, s.morale, s.stance, s.active};
        for (int x : v) fnv(h, x);
    }
    fnv(h, r.finished); fnv(h, r.winner); fnv(h, r.end_reason); fnv(h, r.round);
}
static void hash_state(std::uint32_t &h, const Duel &d) {
    fnv(h, static_cast<int>(d.rng.state)); fnv(h, d.hap); fnv(h, d.round); fnv(h, d.finished); fnv(h, d.winner); fnv(h, d.end_reason);
    for (const Side &sd : d.side) {
        const int v[11] = {sd.active, sd.morale, sd.stance, sd.join_timer, sd.switch_wait, sd.guard, sd.charge, sd.buff[0], sd.buff[1], sd.buff[2], sd.ai_opp};
        for (int x : v) fnv(h, x);
        for (int i = 0; i < sd.count; ++i) { fnv(h, sd.f[i].hp); fnv(h, sd.f[i].injury); fnv(h, sd.f[i].state); }
    }
}
static int hp_sum(const Duel &d, int s) { int t = 0; for (int i = 0; i < d.side[s].count; ++i) t += d.side[s].f[i].hp; return t; }
struct Invariants { bool range = true, codes = true, damage = true, roster = true, cap = true, failed = true, verdict = true, one_side = true, frozen = true; };
static bool state_ok(const Duel &d) {
    for (const Side &sd : d.side) {
        if (sd.count < 1 || sd.count > 3 || sd.active < 0 || sd.active >= sd.count) return false;
        if (sd.morale < 0 || sd.morale > 300 || sd.stance < 0 || sd.stance > 3) return false;
        int fighting = 0;
        for (int i = 0; i < sd.count; ++i) {
            const Fighter &f = sd.f[i];
            if (f.hp < 0 || f.hp > 100 || f.injury < 0 || f.injury > 3 || f.state < 0 || f.state > 2) return false;
            if (f.state == 0) { ++fighting; if (i != sd.active) return false; }
        }
        if (fighting != 1) return false;
    }
    return true;
}
// Plays scenario k to the end; returns the hash of every round result and of the final state.
static std::uint32_t play(int k, Duel &d, Invariants *inv) {
    Lcg g{0};
    int policy[2], fixed[2];
    build(k, d, g, policy, fixed);
    std::uint32_t h = 2166136261u;
    if (inv && !state_ok(d)) inv->range = false;
    while (!d.finished) {
        const int cmd[2] = {command(g, policy[0], fixed[0]), command(g, policy[1], fixed[1])};
        const int before_hp[2] = {hp_sum(d, 0), hp_sum(d, 1)}, before_morale[2] = {d.side[0].morale, d.side[1].morale};
        const RoundResult r = step(d, cmd);
        hash_result(h, r);
        if (!inv) continue;
        if (!state_ok(d)) inv->range = false;
        for (int s = 0; s < 2; ++s) {
            const SideResult &me = r.side[s], &other = r.side[1 - s];
            if (me.code < 0 || me.code > 3 || me.damage < 0) inv->codes = false;
            if ((me.code == CodeBlock || me.code == CodeCounter) && other.damage != 0) inv->codes = false;
            if (me.code == CodeCrit && me.damage <= 0) inv->codes = false;
            if (before_hp[1 - s] - hp_sum(d, 1 - s) != me.damage) inv->damage = false;
            if (me.hp != current(d, s).hp || me.morale != d.side[s].morale || me.stance != d.side[s].stance || me.active != d.side[s].active) inv->damage = false;
            if (me.special_failed && (me.special != -1 || me.damage != 0 || me.move != -1 || d.side[s].morale < before_morale[s])) inv->failed = false;
            if (me.special_preempted && (me.special != -1 || d.side[s].morale < before_morale[s])) inv->failed = false;
            if (me.special >= 0 && d.side[s].morale > before_morale[s] - kCost[me.special]) inv->failed = false;
            if (me.swap_in >= 0 && (me.swap_out < 0 || me.swap_in >= d.side[s].count)) inv->roster = false;
            if (me.join_in >= d.side[s].count) inv->roster = false;
        }
        if (r.side[0].damage > 0 && r.side[1].damage > 0) inv->one_side = false;
        if (d.round > d.cfg.round_cap) inv->cap = false;
        if (!d.finished && (d.round >= d.cfg.round_cap || d.hap >= d.cfg.hit_limit)) inv->cap = false;
        if (d.finished) {
            const int a = current(d, 0).hp, b = current(d, 1).hp;
            if (d.end_reason == EndKo) { if ((a > 0 && b > 0) || d.winner != (a <= 0 && b <= 0 ? 2 : a <= 0 ? 1 : 0)) inv->verdict = false; }
            else if (a <= 0 || b <= 0 || d.winner != (a > b ? 0 : b > a ? 1 : 2)) inv->verdict = false;
            if (r.winner != d.winner || !r.finished) inv->verdict = false;
        }
    }
    hash_state(h, d);
    if (inv) {      // a finished duel does not change any more
        std::uint32_t before = 2166136261u, after = 2166136261u;
        hash_state(before, d);
        const int cmd[2] = {CmdAi, CmdSpecial1};
        const RoundResult r = step(d, cmd);
        hash_state(after, d);
        if (before != after || !r.finished || r.side[0].damage || r.side[1].damage) inv->frozen = false;
    }
    return h;
}

