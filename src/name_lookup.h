static const size_t record_size=0x58;
static unsigned char *find(unsigned char *table,const char *key) {
    for(unsigned char *parent=*reinterpret_cast<unsigned char **>(table+8);parent;
        parent=*reinterpret_cast<unsigned char **>(table+8))
        table=*reinterpret_cast<unsigned char **>(parent+0x20);
    const unsigned count=*reinterpret_cast<const unsigned *>(table+0x18);
    if(!count)return nullptr;
    unsigned char *records=*reinterpret_cast<unsigned char **>(table);
    const unsigned char *wanted=reinterpret_cast<const unsigned char *>(key),first=wanted[0];
    for(unsigned index=0;index<count;++index) {
        unsigned char *record=records+static_cast<size_t>(index)*record_size;
        if(record[0]!=first)continue;
        const unsigned char *a=record,*b=wanted;
        while(*a && *a==*b) {++a;++b;}
        if(*a==*b)return record;
    }
    return nullptr;
}
