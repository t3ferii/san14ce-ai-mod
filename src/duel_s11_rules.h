inline const Fighter &current(const Duel &d, int s) { return d.side[s].f[d.side[s].active]; }
// The opponent fighter side s's AI looks at. San11's AI context caches the opponent's slot (+0x14) and 0x4FB2A0 refreshes it
// only at the start (0x4FB910) and when side s ITSELF swaps (0x509B20): after the other side swaps or brings someone in, this
// side's AI keeps judging the fighter that left (his HP, score, strength) until its own next swap. Kept as in San11.
inline const Fighter &seen(const Duel &d, int s) { return d.side[1 - s].f[d.side[s].ai_opp]; }
inline int eff(const Duel &d, int s, int slot) {
    const Fighter &f = d.side[s].f[slot];
    return effective_strength(f.str, f.injury_start, f.injury);
}
inline int eff(const Duel &d, int s) { return eff(d, s, d.side[s].active); }
// 0x507040: advantage of side s's fighter over the other side's.
inline int adv(const Duel &d, int s) { return duel_advantage(eff(d, s), eff(d, 1 - s)); }
// 0x50D0F0.
inline bool buff_on(const Duel &d, int s, int i) { return d.side[s].buff[i] > 0 || d.side[s].buff[i] == -1; }
inline bool any_buff(const Duel &d, int s) { return buff_on(d, s, 0) || buff_on(d, s, 1) || buff_on(d, s, 2); }
// 0x5083E0: action slot, 투지 cost, and the 합-count gate of action 7.
inline bool legal(const Duel &d, int s, int action) {
    if (action < 0 || action > 7 || !(kSlotEnabled[action] || (action == 3 && d.cfg.retreat))) return false;
    if (d.side[s].morale < kCost[action]) return false;
    return action != 7 || d.hap > 14;
}
inline bool any_legal(const Duel &d, int s) {
    for (int a = 0; a < 8; ++a) if (legal(d, s, a)) return true;
    return false;
}
inline int score(const Duel &d, int s, int slot) { return candidate_score(d.side[s].f[slot].hp, eff(d, s, slot)); }
// 0x4FBA70: best slot over EVERY roster slot (fighting, waiting or not entered); ties keep the earlier slot.
inline int best(const Duel &d, int s) {
    int top = 0, pick = -1;
    for (int i = 0; i < d.side[s].count; ++i) {
        const int v = score(d, s, i);
        if (v > top) { top = v; pick = i; }
    }
    return pick;
}
// 0x4FB3F0: strategy bundle of the current fighter.
inline int bundle(const Duel &d, int s) {
    const Fighter &f = current(d, s);
    return f.lubu_bundle ? 0 : (f.personality >= 0 && f.personality <= 3) ? f.personality + 1 : 1;
}

// ---------------------------------------------------------------- relay
// 0x509B20 / 0x50D120: swap the fighting slot. HP, injury and 투지 stay; buffs, charge and guard clear; both waits redraw.
inline void swap_in(Duel &d, int s, int slot) {
    Side &sd = d.side[s];
    sd.f[sd.active].state = 1;
    sd.f[slot].state = 0;
    sd.active = slot;
    sd.buff[0] = sd.buff[1] = sd.buff[2] = 0;
    sd.charge = 0;
    sd.join_timer = 4 + d.rng.rand(3);
    sd.switch_wait = 4 + d.rng.rand(3);
    sd.guard = 0;
    sd.ai_opp = d.side[1 - s].active;         // 0x4FB2A0, the swapping side's context only
}
// 0x506EE0: a stance change clears the charge counter.
inline void set_stance(Duel &d, int s, int stance) {
    if (d.side[s].stance != stance) d.side[s].charge = 0;
    d.side[s].stance = stance;
}
// CmdSwap target: the waiting (state 1) fighter with the most HP, earlier slot on ties; -1 if none.
inline int manual_swap_target(const Duel &d, int s) {
    const Side &sd = d.side[s];
    int pick = -1;
    for (int i = 0; i < sd.count; ++i)
        if (i != sd.active && sd.f[i].state == 1 && sd.f[i].hp > 0 && (pick < 0 || sd.f[i].hp > sd.f[pick].hp)) pick = i;
    return pick;
}
// deviation (scene, local301, user 「교대하는 무장을 선택할 수 있었으면」): the slot the player chose when it can come in now (waiting,
// HP left, not the fighter), else the engine's own pick.
inline int swap_target(const Duel &d, int s, int want) {
    const Side &sd = d.side[s];
    if (want >= 0 && want < sd.count && want != sd.active && sd.f[want].state == 1 && sd.f[want].hp > 0) return want;
    return manual_swap_target(d, s);
}

// deviation (scene, local305): side s may still switch (cfg.swap_limit 0 = no limit).
inline bool swap_left(const Duel &d, int s) { return d.cfg.swap_limit <= 0 || d.side[s].swaps < d.cfg.swap_limit; }

// ---------------------------------------------------------------- AI (tables at 0x8AFA30; every row rolls its own pct)
// 0x4FBC10: switch to the best slot. Needs another slot that already fought; wait W blocks unless HP <= 20 and W <= 2.
inline int ai_switch(Duel &d, int s) {
    const Side &sd = d.side[s];
    const int o = 1 - s;
    bool other = false;
    for (int i = 0; i < sd.count; ++i) if (i != sd.active && (sd.f[i].state == 0 || sd.f[i].state == 1)) other = true;
    if (!other) return -1;
    const int hp = current(d, s).hp;
    if ((hp > 20 || sd.switch_wait > 2) && sd.switch_wait > 0) return -1;
    const int candidate = best(d, s);
    if (candidate < 0) return -1;
    for (const StrategyRow *r = strategy(bundle(d, s), 3); r->kind != 39; ++r) {
        int p = r->chance;
        if (hp < 31) p = p * imin(30, 45 - hp) / 15;
        if (!d.rng.pct(imin(p, 100))) continue;
        if (hp > 32 && any_buff(d, s)) return -1;
        if ((r->kind == 33 && hp <= r->x) || (r->kind == 34 && current(d, s).a0_zero) ||
            (r->kind == 35 && eff(d, o, sd.ai_opp) - eff(d, s) > r->x) || (r->kind == 36 && candidate != sd.active)) return candidate;
        if (r->kind == 37 && sd.guard > 0) return -1;
        // kind 38 has no case in the EXE: the roll is spent and the next row follows.
    }
    return -1;
}
// 0x4FB6A0: does the AI want a special this 합.
inline int ai_trigger(Duel &d, int s) {
    const Side &sd = d.side[s];
    const int o = 1 - s;
    if (!any_legal(d, s)) return 0;
    for (const StrategyRow *r = strategy(bundle(d, s), 0); r->kind != 39; ++r) {
        if (!d.rng.pct(r->chance)) continue;
        if (r->kind == 8) return 0;
        if ((r->kind == 0 && current(d, s).hp <= r->x) || (r->kind == 1 && sd.morale >= r->x) ||
            (r->kind == 2 && seen(d, s).hp <= r->x) ||
            (r->kind == 3 && (legal(d, s, 6) || legal(d, s, 5)) && any_buff(d, o)) || (r->kind == 4 && legal(d, s, 4)) ||
            (r->kind == 5 && legal(d, s, 1) && !buff_on(d, s, 0)) || (r->kind == 6 && legal(d, s, 2) && !buff_on(d, s, 1)) ||
            r->kind == 7) return 1;
    }
    return 0;
}
// 0x4FBAE0: weighted pick among the legal specials (0:20 1:3 2:3 4:20 5:60 6:20 7:20; an active buff drops its action).
inline int ai_weighted(Duel &d, int s) {
    int cumulative[8] = {}, total = 0;
    for (int a = 0; a < 8; ++a) {
        if (!legal(d, s, a) || a == 3) continue;
        if ((a == 1 || a == 2) && buff_on(d, s, a - 1)) continue;
        total += (a == 1 || a == 2) ? 3 : a == 5 ? 60 : 20;
        cumulative[a] = total;
    }
    const int pick = d.rng.rand(total);
    for (int a = 0; a < 8; ++a) if (pick < cumulative[a]) return a;
    return -1;
}
// 0x4FBFF0: which special. Kind 12 passes a literal -1 in the EXE (never selectable). Kind 15 (retreat) still runs 0x4FBC10
// for its rolls, but action 3 is never legal here unless Config::retreat (deviation), so the row falls through.
// deviation (scene, local306 with Config::swap_limit): a side out of switches counts as having no switch target for kind 15.
inline int ai_special(Duel &d, int s) {
    if (!any_legal(d, s)) return -1;
    for (const StrategyRow *r = strategy(bundle(d, s), 1); r->kind != 39; ++r) {
        if (!d.rng.pct(r->chance)) continue;
        int action = -1;
        switch (r->kind) {
        case 9: action = 7; break;
        case 10: action = 6; break;
        case 11: action = 4; break;
        case 13: action = (legal(d, s, 1) && !buff_on(d, s, 0)) ? 1 : -1; break;
        case 14: action = (legal(d, s, 2) && !buff_on(d, s, 1)) ? 2 : -1; break;
        case 15:
            if (current(d, s).hp <= r->x && !(seen(d, s).hp <= r->x + 10)) {
                const int t = ai_switch(d, s);
                if (t < 0 || t > 3 || t == d.side[s].active || !swap_left(d, s)) action = 3;
            }
            break;
        case 16: action = ai_weighted(d, s); break;
        default: break;
        }
        if (action >= 0 && action < 8 && legal(d, s, action)) return action;
    }
    return -1;
}
// 0x4FC3B0: stance, -1 = keep. Kind 24 reads the landed-hit counter (parent +0x10), kind 32 the charge counter (+0x10C).
inline int ai_stance(Duel &d, int s) {
    const Side &sd = d.side[s];
    const int o = 1 - s, b0 = best(d, s), b1 = best(d, o);
    if (b0 < 0 || b1 < 0) return -1;
    const int hp = current(d, s).hp, ohp = seen(d, s).hp, oa = sd.ai_opp;
    for (const StrategyRow *r = strategy(bundle(d, s), 2); r->kind != 39; ++r) {
        if (!d.rng.pct(r->chance)) continue;
        const int k = r->kind, x = r->x;
        if (k == 17 || (k == 18 && hp >= x) || (k == 19 && hp * 2 <= ohp) || (k == 20 && ohp <= x) || (k == 21 && b1 != oa) ||
            (k == 22 && sd.guard > 0)) return 0;
        if ((k == 23 && b0 != sd.active) || (k == 24 && d.hap >= x)) return 1;
        if ((k == 25 && hp >= x) || (k == 26 && score(d, o, oa) >= score(d, s, sd.active)) || (k == 27 && b0 != sd.active) ||
            (k == 28 && b1 != oa) || (k == 29 && !buff_on(d, s, 0)) || (k == 30 && !buff_on(d, s, 1))) return 2;
        if (k == 31) return 3;
        if (k == 32 && sd.charge >= x) return -1;
    }
    return -1;
}
// deviation (scene, local303, user 「무장이 난입할때도 적용해주면 안되나? 교대할때는 적용X」; cfg.join_cut_den): after a 합's joins the
// weaker of the two fighting slots — a joiner against the fighter it meets, or the two joiners — loses the 무력 gap / join_cut_den
// (rounded up) in HP, at least 1 HP left: the scene's first-pair entry cut (duel_manual_script.h entry_cut) for every pair a join
// makes. A switch (command or AI) never cuts.
inline void join_cut(Duel &d, RoundResult &res) {
    if (d.cfg.join_cut_den <= 0 || (res.side[0].join_in < 0 && res.side[1].join_in < 0)) return;
    const int a = current(d, 0).str, b = current(d, 1).str;
    if (a == b) return;
    const int w = a < b ? 0 : 1, gap = a < b ? b - a : a - b;
    Fighter &f = current(d, w);
    if (f.hp <= 1) return;
    const int cut = (gap + d.cfg.join_cut_den - 1) / d.cfg.join_cut_den, v = f.hp - cut < 1 ? 1 : f.hp - cut;
    res.side[w].join_cut = f.hp - v;
    f.hp = v;
}
// 0x50B970 + 0x508F10 + 0x508F80: a fighter that has not entered yet steps in. The FIRST slot that passes, not the best.
inline int auto_join(Duel &d, int s) {
    const Side &sd = d.side[s];
    const int o = 1 - s;
    bool bench = false;
    for (int i = 0; i < sd.count; ++i) if (i != sd.active && sd.f[i].state == 2) bench = true;
    if (!bench || sd.join_timer > 0) return -1;
    if (current(d, s).hp > 32 && any_buff(d, s)) return -1;
    if (sd.guard > 0) return -1;
    const int a = sd.active, e = d.side[o].active;
    for (int i = 0; i < sd.count; ++i) {
        const Fighter &f = sd.f[i];
        if (f.state != 2) continue;
        if (f.hp < kJoinHp[(f.personality >= 0 && f.personality <= 2) ? f.personality : 3]) continue;
        const JoinRel &r = f.rel;
        const JoinRule rule = join_rule(r.sworn_or_spouse[a] != 0, r.hates_enemy[e] != 0, r.hates_ally[a] != 0,
                                        r.hated_ally_gate[a] != 0, r.loyalty_ac, r.likes_or_kin[a] != 0, r.same_e4[a] != 0,
                                        r.affinity_dist[a]);
        if (!rule.possible || d.hap < rule.min_hap) continue;
        if (d.rng.pct(rule.chance)) return i;
    }
    return -1;
}

// ---------------------------------------------------------------- cycle pieces
// 0x507EE0: end-of-cycle timers. The charge counter grows by 1 and is held at 0 while the guard timer runs.
inline void tick(Duel &d) {
    for (Side &sd : d.side) {
        ++sd.charge;
        if (sd.join_timer > 0) --sd.join_timer;
        if (sd.switch_wait > 0) --sd.switch_wait;
        if (sd.guard > 0) { --sd.guard; sd.charge = 0; }
        for (int &b : sd.buff) if (b > 0) --b;
    }
}
// deviation: non-special HP damage is cut to dmg_num / dmg_den of the San11 value, never below 1 when San11 dealt damage.
inline int scaled(const Duel &d, int damage) { return damage <= 0 ? 0 : imax(1, damage * d.cfg.dmg_num / d.cfg.dmg_den); }
// deviation (scene, local301): the attacker's San14 duel trait bonus (Fighter::power, percent) on a regular hit's San11 damage,
// before the scale (374440 raises the round damage base by the same share). Specials keep their San11 damage.
inline int boosted(const Duel &d, int a, int damage) {
    const int p = d.side[a].f[d.side[a].active].power;
    return damage > 0 && p > 0 ? damage + damage * p / 100 : damage;
}
// 0x50D220: HP stays in 0..100. Returns the HP actually lost.
inline int hurt(Duel &d, int s, int amount) {
    Fighter &f = current(d, s);
    const int before = f.hp;
    f.hp = imax(0, imin(100, f.hp - amount));
    return before - f.hp;
}
// 0x50D2A0: 투지 stays in 0..300.
inline void add_morale(Duel &d, int s, int amount) { d.side[s].morale = imax(0, imin(300, d.side[s].morale + amount)); }

struct Exchange { int move = -1, count = 0, outcome[4] = {}; };
struct HitEvent { int damage, attacker_gain, defender_gain, flag; };
// 0x509480 + 0x50BFA0 once the attacker is known: the move, then every hit outcome (all rolled before any damage).
inline Exchange roll_exchange(Duel &d, int a) {
    Side &sa = d.side[a];
    const Side &sd = d.side[1 - a];
    Exchange x;
    x.move = choose_move(sa.stance, sa.charge, sa.guard, d.rng, buff_on(d, a, 2));
    x.count = x.move == 5 ? 3 + d.rng.rand(2) : 1;
    const int p = adv(d, a);
    for (int i = 0; i < x.count; ++i) x.outcome[i] = hit_outcome(p, sa.stance, sd.stance, sd.guard, eff(d, a), eff(d, 1 - a), d.rng);
    return x;
}
// 0x50C080: one hit's San11 HP damage, both 투지 gains (from the pre-exchange HP) and the landed flag fed to 0x508190.
inline HitEvent exchange_event(const Duel &d, int a, int move, int outcome) {
    const int o = 1 - a;
    const Side &sa = d.side[a], &sd = d.side[o];
    const Regular r = regular_resolve(regular_base(adv(d, a), sa.stance), move, outcome, buff_on(d, a, 0), buff_on(d, o, 1),
                                      sd.stance, sd.guard);
    HitEvent e{r.damage, morale_gain(sa.stance, false, r.attacker_input, current(d, a).hp),
               morale_gain(sd.stance, true, r.defender_input, current(d, o).hp), (move == 6 || move == 7) ? 0 : (outcome != 2 ? 1 : 0)};
    if (move == 7) e.attacker_gain = 100;
    return e;
}
inline void run_exchange(Duel &d, int a, RoundResult &res) {
    const int o = 1 - a;
    const Exchange x = roll_exchange(d, a);
    HitEvent ev[4] = {};
    for (int i = 0; i < x.count; ++i) ev[i] = exchange_event(d, a, x.move, x.outcome[i]);
    res.side[a].move = x.move;
    res.side[a].hits = x.count;
    for (int i = 0; i < x.count; ++i) {
        d.hap += ev[i].flag;
        res.side[a].landed += ev[i].flag;
        res.side[a].damage += hurt(d, o, scaled(d, boosted(d, a, ev[i].damage)));
        add_morale(d, a, ev[i].attacker_gain);
        add_morale(d, o, ev[i].defender_gain);
    }
}
// 0x50AFA0: a special. Damage (0x508B90, not scaled) and the defender's 투지 are fixed first, then the cost, then the effect:
// 1 / 2 set the user's attack / defence buff to -1 (until a swap), 4 rolls an injury, 5 rolls an injury and clears the
// opponent's buffs. Action 0 only deals damage. Counts as one landed hit.
inline void run_special(Duel &d, int s, int action, RoundResult &res) {
    const int o = 1 - s;
    Side &sd = d.side[s];
    res.side[s].special = action;
    const bool hit = special_events(action) != 0;
    const int dmg = hit ? special_damage(adv(d, s), action, buff_on(d, s, 0), buff_on(d, o, 1), d.side[o].stance) : 0;
    const int gain = hit ? morale_gain(d.side[o].stance, true, dmg, current(d, o).hp) : 0;
    add_morale(d, s, -kCost[action]);
    int injured = 0;
    if (action == 1) sd.buff[0] = -1;
    else if (action == 2) sd.buff[1] = -1;
    else if (action == 4 || action == 7) injured = d.rng.pct(injury_chance(adv(d, s)));
    else if (action == 5 || action == 6) {
        if (action == 5) injured = d.rng.pct(injury_chance(adv(d, s)));
        d.side[o].buff[0] = d.side[o].buff[1] = d.side[o].buff[2] = 0;
    }
    if (!hit) return;
    ++d.hap;
    res.side[s].hits = res.side[s].landed = 1;
    res.side[s].damage = hurt(d, o, dmg);
    if (injured) {                                              // 0x508350
        Fighter &f = current(d, o);
        f.injury = imin(3, f.injury + 1);
        res.side[o].injured = true;
    }
    add_morale(d, o, gain);
}
// San11 outcome -> San14 round code (docs/MANUAL_DUEL.md section 6). The contract: a side with code 2 or 3 implies the OTHER
// side dealt 0 this 합.
//   damage dealt by a special (0 / 4 / 5) or by 연속 공격 (move 5)      -> that side 1 (회심)
//   an attack that dealt 0 (all dodged, or stopped by the guard timer)  -> the side that stopped it 2 (막음)
//   nobody attacked (buff 1 / 2, 보호 move 6, 투지 move 7, an empty cycle, both specials failed) -> both 2
//   everything else (full or partial hits, 투지 gains, stance changes)   -> 0
//   3 (반격) is never produced.
inline void set_codes(RoundResult &res) {
    SideResult &a = res.side[0], &b = res.side[1];
    if (a.damage + b.damage == 0) {
        const bool attack0 = a.special == 0 || a.special == 4 || a.special == 5 || (a.move >= 0 && a.move <= 5);
        const bool attack1 = b.special == 0 || b.special == 4 || b.special == 5 || (b.move >= 0 && b.move <= 5);
        if (attack0) b.code = CodeBlock;
        else if (attack1) a.code = CodeBlock;
        else a.code = b.code = CodeBlock;
        return;
    }
    for (SideResult &r : res.side) if (r.damage > 0 && (r.special >= 0 || r.move == 5)) r.code = CodeCrit;
}
// San11 0x50AFA0 case 3 (the 투지 cost, no hit) then state 0x50A9D0 -> 0x507E60: a retreat ends the duel in its own cycle and the
// retreating side loses (+0x588 the other side, +0x58C the retreating one).
// deviation (scene, local306 「1B」): San14 settles a duel on the two fighters' end HP (3747A0 picks the higher one), so a retreating
// fighter with at least the other fighter's HP gives up the difference + 1, shown as the other side's parting hit (both codes 0); it
// never goes below 1 HP (no death or capture: 376540 gates on HP 0), so against a fighter at 1 HP the retreat ends in a draw.
inline void retreat_end(Duel &d, int s, RoundResult &res) {
    const int o = 1 - s;
    Fighter &f = current(d, s);
    const int other = current(d, o).hp;
    if (f.hp >= other) {
        const int want = other > 1 ? other - 1 : 1;
        if (want < f.hp) {
            res.side[s].retreat_cut = f.hp - want;
            res.side[o].damage += f.hp - want;
            res.side[o].code = res.side[s].code = CodeNormal;
            f.hp = want;
        }
    }
    d.finished = true;
    d.end_reason = EndRetreat;
    d.winner = f.hp < other ? o : 2;
}

// ---------------------------------------------------------------- public API
// Start a duel. The caller fills side[].count, side[].f[] (id, str, hp, injury, personality, a0_zero, rel), optionally
// side[].morale, f[].state and cfg. 0x50B400 per side: slot 0 fights, the others have not entered (unless the caller's states
// name exactly one fighting slot), every slot starts in stance 2 (투지 중시)
// and 0x509B20 draws the join timer and the switch wait (4 + R(3) each), side 0 first.
inline void start(Duel &d, std::uint32_t seed) {
    d.rng.state = seed;
    d.hap = 0; d.round = 0; d.finished = false; d.winner = -1; d.end_reason = EndNone; d.extended = false;   // local312: extended per duel
    for (Side &sd : d.side) {
        sd.count = imax(1, imin(3, sd.count));                  // at most 3 per side
        sd.stance = 2; sd.guard = 0; sd.charge = 0; sd.swaps = 0;
        sd.buff[0] = sd.buff[1] = sd.buff[2] = 0;
        sd.morale = imax(0, imin(300, sd.morale));
        int fighting = 0, slot = 0;
        bool valid = true;
        for (int i = 0; i < sd.count; ++i) {
            if (sd.f[i].state < 0 || sd.f[i].state > 2) valid = false;
            if (sd.f[i].state == 0) { ++fighting; slot = i; }
        }
        const bool keep = valid && fighting == 1;               // caller-supplied 참가 상태
        sd.active = keep ? slot : 0;
        for (int i = 0; i < 3; ++i) {
            Fighter &f = sd.f[i];
            if (!keep) f.state = i == 0 ? 0 : 2;
            f.hp = imax(0, imin(100, f.hp));
            f.injury = imax(0, imin(3, f.injury));
            f.injury_start = f.injury;
        }
        sd.join_timer = 4 + d.rng.rand(3);
        sd.switch_wait = 4 + d.rng.rand(3);
    }
    for (int s = 0; s < 2; ++s) d.side[s].ai_opp = d.side[1 - s].active;       // 0x50C420 -> 0x4FB910
}
// One 합. cmd[s]: CmdAi (-1) = the San11 AI plays the side; 0..3 stance; 4..8 specials; 9 swap; 10 retreat (Config::retreat).
inline RoundResult step(Duel &d, const int cmd[2]) {
    RoundResult res;
    const int pick[2] = {d.swap_pick[0], d.swap_pick[1]};
    d.swap_pick[0] = d.swap_pick[1] = -1;
    const auto fill = [&]() {
        for (int s = 0; s < 2; ++s) {
            res.side[s].hp = current(d, s).hp; res.side[s].morale = d.side[s].morale;
            res.side[s].stance = d.side[s].stance; res.side[s].active = d.side[s].active;
        }
        res.round = d.round; res.finished = d.finished; res.winner = d.winner; res.end_reason = d.end_reason;
    };
    if (d.finished) { fill(); return res; }
    ++d.round;
    int request[2] = {-1, -1};
    bool failed[2] = {false, false};
    for (int s = 0; s < 2; ++s) {
        const int action = command_action(cmd[s]);
        if (action < 0) continue;
        if (legal(d, s, action)) request[s] = action;
        else {
            // deviation: a 필살 command without enough 투지 fails: no attack this 합, nothing spent, the side only defends with
            // its current stance (San11's UI simply does not offer the action).
            failed[s] = true;
            res.side[s].special_failed = true;
        }
    }
    // 0x50A0A0: a manual request wins (side 0 first); otherwise each AI side rolls its trigger and pct(50) picks when both want.
    int special_side = request[0] >= 0 ? 0 : request[1] >= 0 ? 1 : -1;
    if (special_side < 0) {
        int want[2] = {0, 0};
        for (int s = 0; s < 2; ++s) if (cmd[s] == CmdAi) want[s] = ai_trigger(d, s);
        if (want[0] && want[1]) {
            if (d.rng.pct(50)) want[0] = 0;
            else want[1] = 0;
        }
        special_side = want[0] ? 0 : want[1] ? 1 : -1;
    }
    if (special_side >= 0) {
        const int s = special_side;
        if (request[1 - s] >= 0) res.side[1 - s].special_preempted = true;
        const int action = request[s] >= 0 ? request[s] : ai_special(d, s);       // 0x507D00
        if (action >= 0 && action < 8) run_special(d, s, action, res);             // 0x4FC790
        // else: the AI wanted a special but 0x4FBFF0 found none; the cycle ends with only the timer tick (0x50BDC0 -> 0xB).
    } else {
        // 0x50BF70 works out both join candidates first; 0x50ADD0 brings them in, side 0 then side 1.
        const int cand[2] = {auto_join(d, 0), auto_join(d, 1)};
        for (int s = 0; s < 2; ++s)
            if (cand[s] >= 0 && cand[s] != d.side[s].active) { swap_in(d, s, cand[s]); res.side[s].join_in = cand[s]; }
        join_cut(d, res);   // deviation, off unless cfg.join_cut_den
        // 0x507C00: manual stances first, then the AI sides'.
        for (int s = 0; s < 2; ++s) if (cmd[s] >= CmdStance0 && cmd[s] <= CmdStance3) set_stance(d, s, cmd[s]);
        for (int s = 0; s < 2; ++s) {
            if (cmd[s] != CmdAi) continue;
            if (d.cfg.force_stance[s] >= 0) set_stance(d, s, d.cfg.force_stance[s]);
            else {
                const int st = ai_stance(d, s);
                if (st >= 0 && st <= 3) set_stance(d, s, st);
            }
        }
        // 0x507DC0 picks the switch targets; 0x50AEF0 applies them, side 0 then side 1.
        int target[2] = {-1, -1};
        for (int s = 0; s < 2; ++s) {
            // deviation (cfg.drop_swap_on_join, user 2026-11-22 「교대」 feedback): a queued manual swap is dropped in a 합 where the side
            // just had a join, so the joiner fights this 합 instead of leaving again at once (off = the parity games' rule).
            // deviation (cfg.swap_limit, local305): a side out of switches neither switches on command nor lets its AI roll for one.
            if (cmd[s] == CmdSwap) target[s] = (d.cfg.drop_swap_on_join && res.side[s].join_in >= 0) || !swap_left(d, s) ? -1 : swap_target(d, s, pick[s]);
            else if (cmd[s] == CmdAi) target[s] = swap_left(d, s) ? ai_switch(d, s) : -1;
        }
        for (int s = 0; s < 2; ++s)
            if (target[s] >= 0 && target[s] != d.side[s].active) {
                res.side[s].swap_out = d.side[s].active;
                swap_in(d, s, target[s]);
                res.side[s].swap_in = target[s];
                ++d.side[s].swaps;
            }
        // 0x50BFA0 / 0x50C080: one side attacks.
        int attacker = -1;
        if (failed[0] && failed[1]) attacker = -1;
        else if (failed[0]) attacker = 1;                       // deviation: no 0x509240 roll, a failed side cannot attack
        else if (failed[1]) attacker = 0;
        else attacker = attacker_side(kStance[d.side[0].stance][0], kStance[d.side[1].stance][0], adv(d, 0), d.rng);
        if (attacker >= 0) run_exchange(d, attacker, res);
    }
    set_codes(res);
    // 0x508980: the fighting slot at HP 0 loses for its side; both at 0 = draw.
    // deviation: (San11's own rule, kept on purpose and listed in the contract) no automatic next fighter when the fighting slot falls.
    const bool dead0 = current(d, 0).hp <= 0, dead1 = current(d, 1).hp <= 0;
    const int retreated = res.side[0].special == 3 ? 0 : res.side[1].special == 3 ? 1 : -1;   // one side's special a cycle
    if (retreated >= 0) {
        retreat_end(d, retreated, res);
    } else if (dead0 || dead1) {
        d.finished = true; d.end_reason = EndKo;
        d.winner = dead0 && dead1 ? 2 : dead0 ? 1 : 0;
    } else {
        bool cap = d.round >= d.cfg.round_cap;
        if (cap && d.hap < d.cfg.hit_limit && d.cfg.round_ext > 0 && !d.extended) {
            // deviation (local312): the cap reached with both standing rolls once; a hit adds round_ext 합 and the duel goes on.
            d.extended = true;
            if (d.rng.rand(100) < d.cfg.round_ext_pct) { d.cfg.round_cap += d.cfg.round_ext; res.extended = true; cap = false; }
        }
        if (cap || d.hap >= d.cfg.hit_limit) {
            // deviation: at the 합 cap (and at San11's own 50 landed hits, 0x50AAA0) the higher fighting HP wins, equal = draw.
            d.finished = true; d.end_reason = cap ? EndRoundCap : EndHitLimit;
            const int a = current(d, 0).hp, b = current(d, 1).hp;
            d.winner = a > b ? 0 : b > a ? 1 : 2;
        } else {
            tick(d);
        }
    }
    fill();
    return res;
}

