// ---------------------------------------------------------------- RNG (0x472490 / 0x472510, state 0x8A2D9C)
struct Rng {
    std::uint32_t state = 0;
    int next() { state = state * 1812433253u + 12345u; return static_cast<int>(state >> 16); }
    // R(n): 0..n-1. n < 2 (or low 16 bits 0) returns 0 WITHOUT advancing the state.
    int rand(int n) { return (n < 2 || (n & 65535) == 0) ? 0 : next() % (n & 65535); }
    // pct(n): n <= 0 returns 0 WITHOUT advancing the state; pct(100) advances and is always true.
    int pct(int n) { return n <= 0 ? 0 : (next() % 100 < n ? 1 : 0); }
};

// ---------------------------------------------------------------- kernels
constexpr int imin(int a, int b) { return a < b ? a : b; }
constexpr int imax(int a, int b) { return a > b ? a : b; }
constexpr int iabs(int a) { return a < 0 ? -a : a; }
constexpr long long advantage_weight(int s, int low, int cap, int step) {
    const int raw = 180 + s - low, u = imin(s - low, cap), v = imax(u - cap + step, 0);
    const long long w = static_cast<long long>(cap - u) * u + (u + 1) * u / 2 + v * imax(v - 1, 0) / 2 + 180 +
                        static_cast<long long>(imax(raw - cap - 181 + step, 0)) * step;
    return w * w;
}
// 0x509C30: weighting 1..99 of effective strength a against b (the other side reads 100 - P).
constexpr int duel_advantage(int a, int b) {
    const int low = imin(a, b), high = imax(a, b);
    const int cap = imax(high - 5, 0) * imax(high - 5, 0) / 1500, step = imax(iabs(a / 10 - b / 10), 1);
    const long long x = advantage_weight(a, low, cap, step), y = advantage_weight(b, low, cap, step);
    return x >= y ? imin(static_cast<int>(x * 100 / (x + y)), 99) : 100 - imin(static_cast<int>(y * 100 / (x + y)), 99);
}
// 0x508AB0: regular base damage.
constexpr int regular_base(int p, int stance) { return imax(3, kStance[stance][6] * (kStance[stance][2] * p / 50) * 7 / 27); }
struct Regular { int damage, attacker_input, defender_input; };
// 0x50B5E0: HP damage and both 투지 inputs of one hit. No 80 cap here.
// deviation: the player / difficulty factors (x11/10, x4/5), the item bits (x9/8, x10/9) and person 0x294's x13/11 are left out.
constexpr Regular regular_resolve(int base, int move, int outcome, bool attack_buff, bool defense_buff, int defender_stance,
                                  int defender_guard) {
    int v = base;
    if (attack_buff) v = v * 5 / 4;
    if (defense_buff) v = v * 3 / 4;
    if (move == 5) v = v * 3 / 4;
    else if (move == 6 || move == 7) return {0, 0, 0};
    if (defender_guard > 0) return {0, 0, (defender_stance == 1 || defender_stance == 2) ? imax(1, v / 2) : 0};
    if (outcome == 1) return {defender_stance == 1 ? imax(1, v * 3 / 10) : v / 2, v * 3 / 4, imax(1, v / 2)};
    if (outcome == 2) return {0, 0, defender_stance == 1 ? v : defender_stance == 2 ? imax(1, v / 2) : 0};
    return {v, v, v};
}
// 0x508B90: special damage, capped at 80.
// deviation: the player / difficulty factors, the item bits and the person-ID factors (x11/10, x13/11) are left out.
constexpr int special_damage(int p, int action, bool attack_buff, bool defense_buff, int defender_stance) {
    int v = p * 20 / 55;
    if (attack_buff) v = v * 5 / 4;
    if (defense_buff) v = v * 3 / 4;
    if (action == 1 || action == 2) v = 0;
    else if (action == 0 || action == 6) v = v * 6 / 5;
    else if (action == 5) v *= 3;
    else if (action == 7) v = v * 3 / 2;
    if (defender_stance == 1) v = v * 3 / 4;
    return imin(v, 80);
}
// 0x4FB980. deviation: the item score 0x58A440 is 0.
constexpr int candidate_score(int hp, int strength) {
    const int s = (strength + 4) / 5;
    return imax(1, ((hp + 9) / 10 + 20) * s * s * 96 / 10);
}
// 0x48A5E0 -> 0x4894D0: an injured stat is stat * (100, 80, 50, 30)% (at least 1).
// deviation: San11's person-ID strength bonuses (+3 / +5 / +10, 0x50CD90) are left out.
// approximation: the caller's 무력 already carries San14's own penalty for the start injury, so only the San11 ratio between the
// current and the start level is applied; San11's upper clamp of 100 is not applied to San14 values.
constexpr int effective_strength(int strength, int injury_start, int injury) {
    return injury == injury_start ? imax(1, strength) : imax(1, strength * kInjuryPct[injury] / kInjuryPct[injury_start]);
}
// 0x509240 with the perspective flag (+0x1C) 0: which side attacks. adv0 = 0x507040(side 0 active vs side 1 active).
// deviation: the item bit 0x10 and person 0x62 terms (+2 / -2) are left out.
inline int attacker_side(int speed0, int speed1, int adv0, Rng &rng) {
    const int total = imax(1, speed0 + speed1);
    const bool zero_fast = speed1 <= speed0;                       // ties favour side 0 (the perspective side)
    const int fast = zero_fast ? 0 : 1, top = zero_fast ? speed0 : speed1, p = zero_fast ? adv0 : 100 - adv0;
    int chance = (p - 50) / 2 + top * 100 / total;
    chance = chance < 2 ? 1 : chance > 98 ? 99 : chance;
    return rng.pct(chance) ? fast : 1 - fast;
}
// 0x5072A0: does the attacker get its stance's critical move.
// deviation: the person-ID bonuses (+2..+12) and the item bit 0x20 (+3) are left out. Literal: the RESULT of pct(5)
// (0 or 1) is added to the charge term; a charge below 6 forces 0 except in stance 3 (always 100).
inline int crit_check(int stance, int charge, Rng &rng, bool buff2 = false) {
    int chance = 100;
    if (stance == 0) chance = rng.pct(5) + charge * 2;
    else if (stance == 1) chance = rng.pct(5) + 5 + charge * 4;
    else if (stance == 2) chance = rng.pct(5) + 5 + charge * 3;
    if (buff2) chance += 5;
    if (charge < 6 && stance != 3) chance = 0;
    return rng.pct(chance);
}
// 0x509480: the attacker's move. 0..4 plain, 5 연속 공격 (3 + R(2) hits at 3/4 damage), 6 보호 (no attack; guard timer 5 + R(5),
// 0x507450), 7 투지 +100 (no attack). Stance 3 rolls among the three. A critical clears the charge counter.
inline int choose_move(int stance, int &charge, int &guard, Rng &rng, bool buff2 = false) {
    if (crit_check(stance, charge, rng, buff2)) {
        int move = -1;
        if (stance == 0) move = 5;
        else if (stance == 1) { if (guard <= 0) move = 6; }
        else if (stance == 2) move = 7;
        else if (guard <= 0 && rng.pct(10)) move = 6;
        else move = rng.pct(20) ? 7 : 5;
        charge = 0;
        if (move == 6) { guard = rng.rand(5) + 5; return 6; }
        if (move >= 0) return move;
    }
    return rng.rand(5);
}
// 0x50A1B0: a missed hit becomes a dodge (1 -> outcome 2) or a partial block (0 -> outcome 1).
inline int dodge_roll(int def_strength, int att_strength, int def_stance, Rng &rng) {
    int v = (def_strength - att_strength) / 3 + 10;
    v = v <= 5 ? 5 : v >= 30 ? 30 : v;
    if (def_stance == 1) v += 25;
    return rng.pct(v);
}
// 0x50BAB0: 0 full hit, 1 partial block, 2 dodge. An active guard timer gives 1 with no roll.
// deviation: the person-ID pair rule (three ids at 0x8365B0: pct(50) -> outcome 1) is left out.
inline int hit_outcome(int p, int att_stance, int def_stance, int def_guard, int att_strength, int def_strength, Rng &rng) {
    if (def_guard > 0) return 1;
    int v = rng.rand(10) + ((100 - kStance[def_stance][3]) * kStance[att_stance][1] / 80) * p * 2 / 100;
    v = v < 11 ? 10 : v > 98 ? 99 : v;
    if (rng.pct(v)) return 0;
    return dodge_roll(def_strength, att_strength, def_stance, rng) ? 2 : 1;
}
// 0x509F20: 투지 gained from an input amount. receiving = the side that was attacked (kind 0), else the attacker (kind 1).
// deviation: the difficulty / player factors (x6/5, x4/5) and the item bit 2 (x3/2) are left out.
constexpr int morale_gain(int stance, bool receiving, int amount, int hp) {
    if (amount <= 0) return 0;
    if (receiving && (stance == 1 || stance == 2) && amount < 5) amount = 5;
    else if (amount < 3) amount = 3;
    int v = kStance[stance][7] * amount / 7;
    if (receiving) v = v * 5 / 4;
    if (hp < 30) v *= 2;
    else if (hp < 50) v = v * 3 / 2;
    return imax(1, v);
}
// 0x50A2B0: injury chance of specials 4 / 5 (P * P / 50, 1..90).
// deviation: the difficulty factors, the person-ID cases and the defender's skill bit 0x20 (chance 0) are left out.
constexpr int injury_chance(int p) { return p * p / 50 < 2 ? 1 : imin(p * p / 50, 90); }
// 0x5070C0: hit events a special makes (1 for 0 and 4..7, 0 for the buffs and the retreat).
constexpr int special_events(int action) { return (action == 0 || (action >= 4 && action <= 7)) ? 1 : 0; }

// What 0x508F80 reads for one bench fighter (the candidate). [a] = toward the ally in slot a (the side's current fighter),
// [e] = toward the enemy in slot e. The caller maps San14 relations; see ENGINE.md for the San11 fields.
struct JoinRel {
    unsigned char sworn_or_spouse[3] = {};   // 0x488CC0 (+0x64 same sworn group) or 0x488C80 (+0x60 spouse id) with ally a
    unsigned char hates_enemy[3] = {};       // 0x488ED0: enemy e is in the candidate's +0x80 list (혐오)
    unsigned char hates_ally[3] = {};        // 0x488ED0: ally a is in the candidate's +0x80 list
    unsigned char hated_ally_gate[3] = {};   // ally a has +0xA0 == 0 (0x489120), a valid vfunc +0x40 value, equal to the candidate's
    unsigned char likes_or_kin[3] = {};      // 0x488E00 (+0x6C list, 친애) or 0x48C0B0 (+0x54 same blood) with ally a
    unsigned char same_e4[3] = {};           // person +0xE4 equal with ally a (meaning not identified)
    unsigned char affinity_dist[3] = {};     // 0x48A450: 상성 distance on the 150 circle, 0..75, to ally a
    unsigned char loyalty_ac = 0;            // candidate byte +0xAC (chance = value >> 2 in the hated-ally branch)
};
struct JoinRule { bool possible; int min_hap, chance; };
// 0x508F80 branch order: who may step in for the current fighter, from which 합 count, with what chance.
constexpr JoinRule join_rule(bool sworn_or_spouse, bool hates_enemy, bool hates_ally, bool hated_ally_gate, int loyalty_ac,
                             bool likes_or_kin, bool same_e4, int affinity_dist) {
    if (sworn_or_spouse) return {true, 3, 80};
    if (hates_enemy) return {true, 4, 60};
    if (hates_ally) return hated_ally_gate ? JoinRule{true, 4, loyalty_ac >> 2} : JoinRule{false, 0, 0};
    if (likes_or_kin) return {true, 6, 50};
    const int v = (75 - affinity_dist) / 2;
    return same_e4 ? JoinRule{true, 6, v + 10} : JoinRule{true, 6, imax(1, v)};
}

