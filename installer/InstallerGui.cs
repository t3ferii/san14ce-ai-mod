    // 값 = 들여쓰기 단계. 종속의 종속(예: 수복 부대의 시설 건설)도 제 상위 바로 아래에 한 단계 더 들여 쓴다.
    // (이전에는 한 단계만 따라가서, 상위가 이미 종속인 기능은 탭에 나오지 않았다.)
    static List<KeyValuePair<Feature, int>> TabOrder(string tab) {
        var items = Catalog.Items.Where(f => f.Tab == tab && !Catalog.Retired.Contains(f.Id)).ToList();
        var order = new List<KeyValuePair<Feature, int>>();
        Action<Feature, int> add = null;
        add = (f, depth) => {
            order.Add(new KeyValuePair<Feature, int>(f, depth));
            foreach (var c in items.Where(c => c.Requires == f.Id)) add(c, depth + 1);
        };
        foreach (var f in items) {
            bool nestedHere = f.IsChild && items.Any(p => p.Id == f.Requires);
            if (!nestedHere) add(f, 0);
        }
        return order;
    }

