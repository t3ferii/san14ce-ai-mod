"""Read-only scan of the verified plain EXE copy: every RTTI class ending in "Node" whose vtable
index 16 (Execute, confirmed on 9 known AI nodes) points into .text. Writes
research/ai_trace/bt_nodes.json and src/ai_trace_nodes.h. No game process access."""
from pathlib import Path
import json,re,struct,sys
P=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(P/'research/ui_atlas'))
from build_catalog import PE
SOURCE=P/'build/ui_native_analysis/editor83_b25953386/game.exe.unpacked.exe'   # decoded 1a4a447d image (build_catalog's own SOURCE is the former build)
EXPECTED='1a4a447d14e68c40ad2a5107c29c7341c10eee8fc297a7b35032900c341dbcaa'
import hashlib
pe=PE(SOURCE);base=pe.base
assert hashlib.sha256(pe.data).hexdigest()==EXPECTED
def q(r):return struct.unpack('<Q',pe.read(r,8))[0]
def d(r):return struct.unpack('<I',pe.read(r,4))[0]
# Known Execute slots from earlier verified hooks: index 16 of each RTTI vtable.
# (the former build's slots 1344518/1343C98/134B4F8/134AF00/13491B0/134CDF8/13463B0/1346E70/134C8F8, mapped by their execute functions' masked prologues)
KNOWN={0x1347518:0x201C0,0x1346C98:0x1F380,0x134E518:0x69AB0,0x134DF20:0x61C90,0x134C1D0:0x54250,
       0x134FE18:0x7C300,0x13493D8:0x2D720,0x1349E98:0x36E80,0x134F918:0x7B0B0}
rd=next(s for s in pe.sections if s['name']=='.rdata');tx=next(s for s in pe.sections if s['name']=='.text')
blob=pe.data[rd['offset']:rd['offset']+rd['size']]
lo,hi=base+rd['rva'],base+rd['rva']+rd['virtual_size'];tlo,thi=base+tx['rva'],base+tx['rva']+tx['virtual_size']
nodes=[]
for off in range(0,len(blob)-8,8):
    col=struct.unpack_from('<Q',blob,off)[0]
    if not lo<=col<hi:continue
    try:
        c=col-base
        if d(c)!=1:continue
        name=pe.read(d(c+12)+16,160).split(b'\0')[0].decode('latin1')
    except Exception:continue
    if not(name.startswith('.?AV') and name.endswith('Node@@')):continue
    vt=rd['rva']+off+8;ex=q(vt+128)
    if tlo<=ex<thi:nodes.append({'class':name[4:-2],'vtable':hex(vt),'execute_slot':hex(vt+128),'execute':hex(ex-base)})
slots={int(n['execute_slot'],16):int(n['execute'],16) for n in nodes}
for s,e in KNOWN.items():assert slots.get(s)==e,hex(s)
assert len(slots)==len(nodes)
(P/'research/ai_trace').mkdir(parents=True,exist_ok=True)
(P/'research/ai_trace/bt_nodes.json').write_text(json.dumps(nodes,indent=1)+'\n',encoding='utf-8')
key=re.compile(r'Depat|Departure|Purpose|SetTarget|TargetTroops|Relay|Retreat|ArmyAction|Execute(Area|Foothold|Intercept|Facility|Attack|Construct|Attract|AutoPaint)|Virtual|DecideArea|Cut|Logistics|Occupy|MoveAdvantage|MoveObject|ForceCommandMove|CommandExecutionMove|Caution.*(Add|Remove|Clear|Update|Evaluation)')
watch=re.compile(r'Army|Troops|Relay|Target|Sortie|Attack|Retreat|Move|Occupy|Foothold|Cut|Logist|Siege|Battle|Front|March|Depart|Depat|Intercept|Route|Hex|Caution|Defend|Facility|Construct|Build|Fire|Evade|Advantage|Supply|Transport|Purpose|Attract|Paint')
out=['// Generated by tools/gen_ai_trace_nodes.py from the verified plain EXE RTTI (read-only scan).',
     '// Every native behaviour-tree node: Execute = vtable index 16. watch=1: army/troops state is compared',
     '// around the call; key=1: every call is also logged. Other nodes are only counted.',
     '#include "game_addresses.h"',
     'struct TraceNode {unsigned slot,execute;bool watch,key;const char *name;};',
     'static const TraceNode trace_nodes[]={']
for n in nodes:
    k=bool(key.search(n['class']));w=k or bool(watch.search(n['class']))
    # user 2026-11-05: original addresses are address table ids (src/game_addresses.h); new rows need their ids added with tools/gen_signatures.py first
    out.append('    {GA(GA_%X),GA(GA_%X),%d,%d,"%s"},'%(int(n['execute_slot'],16),int(n['execute'],16),w,k,n['class']))
out.append('};')
(P/'src/ai_trace_nodes.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
print(json.dumps({'status':'ai_trace_nodes_generated','nodes':len(nodes),'key_nodes':sum(1 for n in nodes if key.search(n['class'])),'watched_nodes':sum(1 for n in nodes if key.search(n['class']) or watch.search(n['class']))}))
