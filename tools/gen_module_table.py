def emit_table(ordered, reg):
    out = [HEADER, '#include "module_overlay_subscriptions.inl"\n']
    out.append('// Activation order of the convenience module (one row per former split_activate statement).\n')
    out.append('static const char *const kModuleNames[]={\n' + ''.join('    "%s",\n' % r['name'] for r in ordered) + '};\n')
    adds = [s for s in reg.get('subscriptions', []) if s['kind'] == 'add']
    out.append('// Service subscriptions (service, owner, order, gate order); the fixture proves the call order for every registration order.\n')
    out.append('struct ModuleSubscription {const char *service,*owner;unsigned order,gate_order;};\n')
    out.append('static const ModuleSubscription kSubscriptions[]={\n' + ''.join(
        '    {"%s","%s",%d,%d},\n' % (s['service'], s['owner'], s['order'], s['gate_order']) for s in adds) + '};\n')
    out.append('#ifndef MODULE_TABLE_NAMES_ONLY\n')
    out.append('// {name, feature id for feature_off logs (0 none), wanted, install (false = refused), refused}\n')
    out.append('static const ModuleDesc kModules[]={\n')
    for r in ordered:
        cond = r.get('cond', '')
        if cond:
            out.append('#if %s\n' % cond)
        refused = r.get('refused', '')
        out.append('    {"%s",%d,[]{return %s;},[]{return %s;},[]{%s}},\n' % (
            r['name'], r.get('off_id', 0), r['wanted'], r['install'], (refused + ';') if refused else ''))
        if cond:
            out.append('#endif\n')
    out.append('};\n')
    out.append('// Joins every module to the services it uses (prepare time, before any hook is published); see core_services.h.\n')
    out.append('static void module_subscribe_all() {\n')
    overlay_done = False
    for s in reg.get('subscriptions', []):
        cond = s.get('cond', '')
        if s['service'] == 'overlay':
            if overlay_done:
                continue
            overlay_done = True
            out.append('#if %s\n    MODULE_SUBSCRIBE_OVERLAY();\n' % cond)
            for o in reg['subscriptions']:
                if o['service'] == 'overlay' and o['kind'] == 'add':
                    out.append('    log_event("overlay_sub",%d,%d,0);\n' % (o['order'], o['gate_order']))
            out.append('#endif\n')
            continue
        if cond:
            out.append('#if %s\n' % cond)
        out.append('    %s;\n' % s['expr'])
        if cond:
            out.append('#endif\n')
    out.append('    // svc_install: service id, subscriber count, hash of the owners in call order (tests/core_services_fixture.cpp prints the expected ones)\n')
    for name, ident in SERVICES.items():
        out.append('    log_event("svc_install",%d,services::%s.count,services::%s.order_hash());\n' % (ident, name, name))
    for name, (ident, variable) in PLUGIN_SERVICES.items():
        out.append('    log_event("svc_install",%d,%s.count,%s.order_hash());\n' % (ident, variable, variable))
    out.append('}\n#endif\n')
    return ''.join(out)


def emit_overlay(reg):
    out = [HEADER, '#pragma once\n// Rows of the overlay service (draw order terrain, sprites, preview, briefing); includes core_services.h users only.\n',
           '#define MODULE_SUBSCRIBE_OVERLAY() do { \\\n']
    for s in reg.get('subscriptions', []):
        if s['service'] == 'overlay' and s['kind'] == 'add':
            out.append('    %s; \\\n' % s['expr'])
    out.append('} while(0)\n')
    return ''.join(out)


def emit_flags(reg):
    return (HEADER + '#pragma once\n'
            '// Every bool flag of ModFeatures (the adapter builds member pointers from it, fixtures build a mirror struct).\n'
            '#define MODULE_FLAG_LIST(X) \\\n' + ' \\\n'.join('    X(%s)' % f for f in reg['flags']) + '\n')


CLOSURE_BODY = '''// Transitive; returns the number of flags switched off. feature_off(100+flag index, reason 6 = parent off, 100+parent index) is
// logged for each (reasons 1-5 are the install-time ones).
static unsigned feature_off_closure(ModFeatures &f) {
    unsigned changed=0;
    for(bool again=true;again;) {
        again=false;
        for(const auto &r:kFeatureRequires)if(f.*r.c && !(f.*r.p)) {
            f.*r.c=false;again=true;++changed;
            log_event("feature_off",100u+r.child_index,6u,100u+r.parent_index);
        }
    }
    return changed;
}
'''


def emit_closure(reg):
    flags = reg['flags']
    idx = {f: i for i, f in enumerate(flags)}
    out = [HEADER, '#include "module_flags.h"\n',
           'struct FeatureFlag {const char *name;bool ModFeatures::*member;};\n',
           '#define MODULE_FLAG_ROW(n) {#n,&ModFeatures::n},\n',
           'static const FeatureFlag kFeatureFlags[]={MODULE_FLAG_LIST(MODULE_FLAG_ROW)};\n',
           '#undef MODULE_FLAG_ROW\n',
           '// Hard requires between flags: a child whose parent is off goes off too.\n',
           'struct FeatureRequire {const char *child,*parent;bool ModFeatures::*c;bool ModFeatures::*p;unsigned child_index,parent_index;};\n',
           'static const FeatureRequire kFeatureRequires[]={\n']
    for q in reg['requires']:
        out.append('    {"%s","%s",&ModFeatures::%s,&ModFeatures::%s,%d,%d},\n' % (
            q['child'], q['parent'], q['child'], q['parent'], idx[q['child']], idx[q['parent']]))
    out.append('};\n')
    out.append(CLOSURE_BODY)
    return ''.join(out)


def emit_module_docs(features):
    """Keep the code map in sync with the same manifest used by check selection."""
    out = ['# 기능별 코드 지도\n\n',
           '<!-- generated by tools/gen_module_table.py from development/features.json; do not edit -->\n\n',
           'DLL은 로더·전투·편의·CCZ·Layout 다섯 개다. 아래 host는 논리 모듈의 소유 DLL이며, '
           '`tool`은 개발 도구다. 설치 상태는 [CURRENT](../development/CURRENT.md)를 따른다.\n\n',
           '아래 경로는 프로젝트 기준이다. `owns`는 소유 범위, `sources`는 조사·검사 입력이다. '
           '파일 소유가 설치·게시를 뜻하지는 않는다. 실제 포함·게시 조건은 '
           '`development/module_registry.json`과 생성된 `src/module_unity_*.inl`·`src/module_pointers.inl`에서 확인한다.\n\n',
           '| 모듈 | 상태 / host / 빌드 | 의존 | 소유 파일 | 조사 입력 | 검사 경로 |\n',
           '|---|---|---|---|---|---|\n']
    def cell(values):
        return '<br>'.join('`%s`' % str(v).replace('|', '&#124;') for v in values) or '—'
    for name, mod in sorted(features['modules'].items()):
        deps = list(mod.get('depends', []))
        if mod.get('alias_of'):
            deps.append('alias_of=' + mod['alias_of'])
        out.append('| `%s` | %s / %s / %s | %s | %s | %s | %s |\n' % (
            name, mod['status'], mod['dll'], mod['build'], cell(deps), cell(mod.get('owns', [])),
            cell(mod.get('sources', [])), cell(mod.get('tests', []))))
    out += ['\n`tools/check_feature.ps1 -Feature <모듈> -List`로 실행 계획을 확인한다. '
            '표는 `python -X utf8 tools/gen_module_table.py`로 재생성하며 `--check`가 불일치를 거부한다.\n\n',
            '규칙·근거: [SESSION_RULES](SESSION_RULES.md), [스위치](FEATURE_SWITCHES.md), '
            '[원작 통합 조사본](../../San14Sim/docs/orig/README.md), [NATIVE_FUNCTIONS](NATIVE_FUNCTIONS.md), '
            '[문서 이력](HISTORY.md).\n']
    return ''.join(out)


def main():
    check = '--check' in sys.argv
    reg = load(REGISTRY)
    features = load(FEATURES)
    errs = validate(reg, features)
    ordered = order_rows(reg['rows'])
    names = [r['name'] for r in ordered]
    if '--order' in sys.argv:
        print('\n'.join(names))
        return 0
    with open(os.path.join(ROOT, BASELINE), encoding='utf-8') as f:
        baseline = [l.strip() for l in f if l.strip() and not l.startswith('#')]
    if names != baseline:
        errs.append('activation order differs from %s' % BASELINE)
    outputs = {OUT_TABLE: emit_table(ordered, reg), OUT_CLOSURE: emit_closure(reg), OUT_FLAGS: emit_flags(reg), OUT_OVERLAY: emit_overlay(reg)}
    outputs[OUT_POINTERS] = emit_pointers(reg)
    outputs[OUT_DOC] = emit_module_docs(features)
    if reg.get('unity'):
        outputs[OUT_UNITY] = emit_unity_selector()
        for which, rel in UNITY_LISTS.items():
            outputs[rel] = emit_unity_list(reg, which)
            if which in UNITY_ROOT_DEFINE:
                for unit in unit_names(reg, which):
                    outputs[unit_tu_path(which, unit)] = emit_unit_tu(reg, which, unit)
    if check:
        for rel, text in outputs.items():
            path = os.path.join(ROOT, rel)
            have = open(path, encoding='utf-8', newline='').read() if os.path.exists(path) else None
            if have != text:
                errs.append('%s is stale; run tools/gen_module_table.py' % rel)
        for e in errs:
            print('gen_module_table: ' + e)
        print('gen_module_table %s (%d rows, %d flags, %d requires)' % ('FAILED' if errs else 'PASSED', len(names), len(reg['flags']), len(reg['requires'])))
        return 1 if errs else 0
    if errs:
        for e in errs:
            print('gen_module_table: ' + e)
        return 1
    for rel, text in outputs.items():
        with open(os.path.join(ROOT, rel), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    print('gen_module_table wrote %d rows' % len(names))
    return 0


if __name__ == '__main__':
    sys.exit(main())
