"""Freeze Korean reference labels into the candidate, with source fingerprints."""
from pathlib import Path
import hashlib, json
P=Path(__file__).resolve().parents[1]
refs=P.parent/'reference_mod/Editor_Source/san14ce/refs'
out=['// Generated by tools/generate_unified_labels.py; labels only, no game addresses.', '#pragma once', 'namespace unified_labels {']
for name in ['tactics','personalities','policies','doctrines','formations','books','cities','gates']:
    path=refs/(name+'.json');raw=path.read_bytes();data=json.loads(raw.decode('utf-8-sig'))
    size=max(int(k) for k in data if k.isdecimal())+1
    out.append('// '+name+' source SHA256 '+hashlib.sha256(raw).hexdigest())
    out.append('static constexpr const wchar_t *'+name+'[] = {')
    for i in range(size):
        value=data.get(str(i),'#'+str(i))
        out.append('    L'+json.dumps(value,ensure_ascii=False)+',')
    out.append('};')
out.append('}')
(P/'src/unified_labels.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
print('Frozen labels:',len(out),'lines; no runtime reference-folder dependency')
