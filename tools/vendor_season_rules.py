def once(text, old, new, what):
    n = text.count(old)
    if n != 1:
        sys.exit('vendor: %s matched %d times' % (what, n))
    return text.replace(old, new)


def cut(text, start, end, what, keep_end=True, new=''):
    a = text.find(start)
    if a < 0 or text.find(start, a + 1) >= 0:
        sys.exit('vendor: start of %s not unique' % what)
    b = text.find(end, a)
    if b < 0:
        sys.exit('vendor: end of %s not found' % what)
    if not keep_end:
        b += len(end)
    return text[:a] + new + text[b:]


